    <p class="judulberita">RoboDog Kendali Jarak Jauh, Inovasi ITS bersama Indosat, Nokia, dan NVIDIA
        <span id="bikinjaditengah"><br>Published<br>
            Minggu, 1 Maret 2026</span>
    </p>

    <p>
        <center><img
                src="https://www.its.ac.id/news/wp-content/uploads/sites/2/2026/03/kerjasama-robodog-2-1024x682.jpeg"
                width="600px" height="400px" alt=""></center>
    </p>
    <p class="judulgambar"> Demonstrasi RoboDog untuk mengidentifikasi kurir pengirim paket dengan kontrol jarak jauh
    </p>

    <p>Surabaya, ITS News — <a href="https://www.its.ac.id/" target="_blank">Institut Teknologi Sepuluh Nopember
            (ITS)</a> kembali menegaskan kapasitasnya dalam pengembangan
        robotika dan artificial intelligence (AI). Kali ini, ITS bersama Indosat Ooredoo Hutchison (IOH), Nokia, NVIDIA
        memperkenalkan inovasi RoboDog, robot anjing otonom dengan kendali ribuan kilometer di AI-Ran Research Center,
        Surabaya, Sabtu (28/2).</p>

    <p>Sinergi empat institusi menjadi kunci terwujudnya inovasi ini. IOH memimpin pengembangan Artificial Intelligence
        Radio Access Network (AI-RAN), sementara Nokia menghadirkan infrastruktur jaringan 5G sebagai tulang punggung
        konektivitas. Di sisi lain, NVIDIA mendukung komputasi berbasis Graphics Processing Unit dan ITS
        mengintegrasikannya ke dalam fisik robotika yang siap dioperasikan.</p>

    <p>
        <center><img
                src="https://www.its.ac.id/news/wp-content/uploads/sites/2/2026/03/kerjasama-robodog-3-1024x712.jpeg"
                width="600px" height="400px" alt="" class="formatgambar"></center>
    </p>
    <p class="judulgambar">Perwakilan Pengembang RoboDog ITS Yuke Brilliant Hestiavin memaparkan bahwa RoboDog dirancang
        mampu menerima
        perintah suara manusia dan memahami konteks instruksi. Tak hanya itu, sensor kamera dan LiDAR RoboDog
        memungkinkan robot untuk membaca kondisi sekitar secara real-time. “Kemampuan ini dapat dikendalikan dalam jarak
        ribuan kilometer,” ungkap Yuke.</p>

    <p>Dalam skenario demonstrasi, RoboDog di Surabaya, Indonesia dapat menerima perintah suara dari pengguna di
        Barcelona, Spanyol untuk memeriksa kondisi suatu lokasi, mendeteksi potensi bahaya, hingga memastikan tidak ada
        aktivitas mencurigakan. Mahasiswa Departemen Teknik Komputer ITS tersebut menilai bahwa kemampuan robot untuk
        memahami situasi membuatnya aplikatif untuk industri yang berisiko tinggi bagi manusia.</p>

    <p>Perwakilan Pengembang RoboDog ITS Yuke Brilliant Hestiavin saat mempersiapkan RoboDog untuk demonstrasi
        pengendalian jarak jauh di Kantor Indosat Surabaya</p>

    <p>Di balik kecanggihan itu, VP Head of Technology Strategy & Partnership Management IOH Irwan Radius menyebut
        AI-RAN sebagai fondasi sistem. AI-RAN menghubungkan perintah dari jarak jauh dengan aksi robot melalui jaringan
        5G. “Teknologi ini memungkinkan sinkronisasi antara pusat pemantauan di Spanyol dan robot di Surabaya dengan
        jeda sangat rendah,” klaim Irwan.</p>

    <p>Melalui pendekatan ini, lanjut Irwan, kecerdasan buatan tidak lagi diproses di server terpusat yang jauh,
        melainkan diintegrasikan pada infrastruktur jaringan 5G. Jaringan yang semula hanya berperan sebagai pengirim
        data, kini dapat menjadi pusat pemrosesan komputasi berbasis AI. “Arsitektur ini memungkinkan latensi
        ultra-rendah yang dibutuhkan untuk pengembangan AI berbentuk fisik seperti robotika dan drone otonom,” paparnya.
    </p>

    <p>Perwakilan Pengembang RoboDog menyimulasikan tampilan user interface RoboDog ketika robot dikendalikan dari
        Barcelona, Spanyol</p>

    <p>Implementasi teknologi tersebut akan dipamerkan dalam ajang Mobile World Congress 2026 yang digelar di Barcelona,
        Spanyol, pada Maret 2026 mendatang. Irwan menilai partisipasi ini menjadi penegasan bahwa Indonesia tidak
        sekadar menjadi pasar bagi teknologi AI, tetapi juga mampu menciptakannya. “Semoga melalui forum internasional
        ini, inovasi anak bangsa semakin mendapat ruang dan peluang kolaborasi di kancah global,” tutupnya penuh harap.
    </p>

    <p>Partisipasi ITS mencerminkan kapasitas sumber daya manusia dalam merancang inovasi robotika dan kecerdasan buatan
        yang relevan bagi industri masa depan. Langkah ini sejalan dengan Sustainable Development Goals (SDGs),
        khususnya poin 4 tentang Pendidikan Berkualitas serta poin 9 tentang Industri, Inovasi, dan Infrastruktur.
        Selain itu, juga mendukung poin 17 mengenai Kemitraan untuk Mencapai Tujuan. (HUMAS ITS)</p>

